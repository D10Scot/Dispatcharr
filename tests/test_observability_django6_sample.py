"""Observability spec D9 / O5's first task: the attribute keys each instrumentation emits.

D9's span allowlist rests on a recorded sample, not on memory. This test drives
one request, one task (run and publish), one query, one Redis command and one
outbound call through the five instrumentations on the Django this repository
pins, and compares the keys they emit with the committed fixture
``tests/fixtures/otel_django6_sample.json``. It doubles as the Django 6
compatibility smoke test: upstream's tox matrix covers Django only up to 5.x.

When an instrumentation upgrade changes what it emits, this test reddens and
the fixture is regenerated by running it with ``UPDATE_OTEL_SAMPLE=<path>`` in
the environment (the test container mounts the repository read-only, so the
path is where to write the new JSON; copy it over the fixture). The diff then
shows exactly which key appeared, and D9's allowlist
(``dispatcharr/observability/redaction.py``) is reviewed against it: a new key
is allowed only with a validator.
"""
import json
import os
from pathlib import Path

import psycopg
import redis
import requests
from celery import Celery
from django.conf import settings
from django.db import connection
from django.test import Client, TestCase, override_settings
from django.urls import path
from opentelemetry.instrumentation.celery import CeleryInstrumentor
from opentelemetry.instrumentation.django import DjangoInstrumentor
from opentelemetry.instrumentation.psycopg import PsycopgInstrumentor
from opentelemetry.instrumentation.redis import RedisInstrumentor
from opentelemetry.instrumentation.requests import RequestsInstrumentor
from opentelemetry.sdk.metrics import MeterProvider
from opentelemetry.sdk.metrics.export import InMemoryMetricReader
from opentelemetry.trace import SpanKind

from tests.otel_rig import SENTINEL, Rig, reset_semconv

FIXTURE = Path(__file__).resolve().parent / "fixtures" / "otel_django6_sample.json"

# Keys whose presence depends on how the test environment reaches Postgres,
# Redis and the request (a unix socket has no port; the test client names no
# peer). They are left out of the comparison so CI and a laptop agree; each is
# governed by the allowlist table or dropped by it regardless.
ENVIRONMENT_DEPENDENT_KEYS = frozenset(
    {"server.address", "server.port", "client.address", "network.peer.address", "network.peer.port"}
)


def _boom(request):
    raise ValueError(SENTINEL)


urlpatterns = [path("boom/", _boom)]


class Django6SampleTests(TestCase):
    @classmethod
    def setUpClass(cls):
        super().setUpClass()
        reset_semconv()
        cls.rig = Rig(views=False)
        cls.reader = InMemoryMetricReader()
        cls.rig.meter_provider = MeterProvider(metric_readers=[cls.reader])
        cls.rig.instrument(
            DjangoInstrumentor(),
            CeleryInstrumentor(),
            PsycopgInstrumentor(),
            RedisInstrumentor(),
            RequestsInstrumentor(),
        )

    @classmethod
    def tearDownClass(cls):
        cls.rig.teardown()
        super().tearDownClass()

    def _record(self, scope_suffix, kind, action):
        self.rig.raw.clear()
        action()
        spans = [
            s
            for s in self.rig.raw.get_finished_spans()
            if s.instrumentation_scope.name.endswith(scope_suffix) and s.kind is kind
        ]
        self.assertTrue(spans, f"no {scope_suffix} {kind.name.lower()} span recorded")
        span = spans[-1]
        return {
            "scope": span.instrumentation_scope.name,
            "kind": kind.name,
            "attribute_keys": sorted(set(span.attributes) - ENVIRONMENT_DEPENDENT_KEYS),
            "status": span.status.status_code.name,
            "status_has_description": bool(span.status.description),
            "event_names": sorted({e.name for e in span.events}),
            "event_attribute_keys": sorted({k for e in span.events for k in e.attributes}),
        }

    def _scenarios(self):
        client = Client(raise_request_exception=False)
        sample = {}

        def ok_request():
            client.get(f"/live/user1/{SENTINEL}/42?password={SENTINEL}")

        def raising_request():
            with override_settings(ROOT_URLCONF=__name__):
                Client(raise_request_exception=False).get("/boom/")

        def unrouted_request():
            client.get(f"/api/no/such/{SENTINEL}")

        sample["django_request"] = self._record("django", SpanKind.SERVER, ok_request)
        sample["django_unrouted_api_path"] = self._record("django", SpanKind.SERVER, unrouted_request)
        sample["django_view_raises"] = self._record("django", SpanKind.SERVER, raising_request)

        def query_ok():
            conn = psycopg.connect(**connection.get_connection_params())
            try:
                conn.cursor().execute("SELECT 1")
            finally:
                conn.close()

        def query_error():
            conn = psycopg.connect(**connection.get_connection_params())
            try:
                with self.assertRaises(psycopg.Error):
                    conn.cursor().execute(f"SELECT '{SENTINEL}' FROM")
            finally:
                conn.close()

        sample["psycopg_query"] = self._record("psycopg", SpanKind.CLIENT, query_ok)
        sample["psycopg_query_error"] = self._record("psycopg", SpanKind.CLIENT, query_error)

        redis_client = redis.Redis(host=settings.REDIS_HOST, port=settings.REDIS_PORT, db=int(settings.REDIS_DB))

        def redis_ok():
            redis_client.set("otel-sample-key", "v")
            redis_client.delete("otel-sample-key")

        def redis_error():
            with self.assertRaises(redis.ResponseError):
                redis_client.execute_command("NOSUCHCMD", SENTINEL)

        sample["redis_command"] = self._record("redis", SpanKind.CLIENT, redis_ok)
        sample["redis_command_error"] = self._record("redis", SpanKind.CLIENT, redis_error)

        class Failing(requests.adapters.HTTPAdapter):
            def send(self, request, **kwargs):
                raise requests.exceptions.ConnectionError(f"Max retries exceeded with url: /{SENTINEL}")

        def outbound_error():
            session = requests.Session()
            session.mount("http://", Failing())
            with self.assertRaises(requests.exceptions.ConnectionError):
                session.get(f"http://h/{SENTINEL}?password={SENTINEL}")

        sample["requests_call_error"] = self._record("requests", SpanKind.CLIENT, outbound_error)

        app = Celery("sample", broker="memory://")

        @app.task(name="tests.sample.fails")
        def fails(arg):
            raise ValueError(f"bare {arg}")

        sample["celery_task_run_error"] = self._record(
            "celery", SpanKind.CONSUMER, lambda: fails.apply(args=[SENTINEL])
        )
        sample["celery_task_publish"] = self._record(
            "celery", SpanKind.PRODUCER, lambda: fails.apply_async(args=[SENTINEL])
        )
        return sample

    def _metric_keys(self):
        data = self.reader.get_metrics_data()
        keys = {}
        for rm in data.resource_metrics:
            for sm in rm.scope_metrics:
                for metric in sm.metrics:
                    if metric.name != "http.server.request.duration":
                        continue
                    keys[metric.name] = sorted(
                        {k for point in metric.data.data_points for k in point.attributes}
                        - ENVIRONMENT_DEPENDENT_KEYS
                    )
        return keys

    def test_attribute_keys_match_the_recorded_sample(self):
        sample = self._scenarios()
        sample["metrics"] = self._metric_keys()
        self.assertIn(
            "http.server.request.duration",
            sample["metrics"],
            "no http.server.request.duration point: the semconv opt-in did not contain http",
        )
        update_to = os.environ.get("UPDATE_OTEL_SAMPLE")
        if update_to:
            Path(update_to).write_text(json.dumps(sample, indent=2, sort_keys=True) + "\n")
            self.skipTest(f"sample written to {update_to}; copy it over {FIXTURE.name} and re-run")
        recorded = json.loads(FIXTURE.read_text())
        self.assertEqual(
            sample,
            recorded,
            "an instrumentation emits different keys than the committed sample; review "
            "SPAN_ATTRIBUTE_RULES in dispatcharr/observability/redaction.py and regenerate "
            "the fixture with UPDATE_OTEL_SAMPLE=<path>",
        )

    def test_every_sampled_key_is_either_allowed_or_deliberately_dropped(self):
        """A key the allowlist neither names nor knowingly drops is a decision nobody made."""
        from dispatcharr.observability.redaction import SPAN_ATTRIBUTE_RULES

        deliberately_dropped = {
            "url.full", "user_agent.original",
            "db.statement", "db.user", "db.redis.args_length", "db.redis.pipeline_length",
            "network.transport", "network.protocol.version",
            "celery.delivery_info", "celery.hostname", "messaging.destination_kind",
            "messaging.destination", "exception.message", "exception.stacktrace",
            "exception.escaped",
        }
        recorded = json.loads(FIXTURE.read_text())
        undecided = set()
        for name, entry in recorded.items():
            if name == "metrics":
                continue
            undecided |= set(entry["attribute_keys"]) - set(SPAN_ATTRIBUTE_RULES) - deliberately_dropped
        self.assertEqual(undecided, set(), "sampled keys with no allow rule and no recorded decision to drop")
